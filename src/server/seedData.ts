import crypto from 'crypto';
import { DatabaseState } from '../types/brc';

export function hashPassword(plain: string): string {
  const salt = 'brc_zhob_2016_salt';
  const derived = crypto.scryptSync(plain, salt, 32).toString('hex');
  return `$scrypt$brc$${derived}`;
}

export function verifyPassword(plain: string, storedHash: string): boolean {
  return hashPassword(plain) === storedHash;
}

export function stripDemoMarkers<T>(input: T): T {
  if (typeof input === 'string') {
    return input
      .replace(/\s*\[DEMO\s*-\s*Confirm with BRC\]/gi, '')
      .replace(/\s*\[DEMO\]/gi, '')
      .trim() as unknown as T;
  }
  if (Array.isArray(input)) {
    return input.map((item) => stripDemoMarkers(item)) as unknown as T;
  }
  if (input && typeof input === 'object') {
    const out: Record<string, any> = {};
    for (const [k, v] of Object.entries(input)) {
      if (k === 'is_demo' || k === 'is_demo_notice_visible') {
        out[k] = false;
      } else {
        out[k] = stripDemoMarkers(v);
      }
    }
    return out as T;
  }
  return input;
}

